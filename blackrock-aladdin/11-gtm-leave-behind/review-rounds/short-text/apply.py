def apply(html, entries, svg):
    """Apply entries in order. An entry whose `old` is absent but whose `new` is
    already present is reported as already applied (idempotent re-runs)."""
    bad = False
    done = 0
    for entry in entries:
        iid, old, new = entry[0], entry[1], entry[2]
        want = entry[3] if len(entry) > 3 else 1
        n = html.count(old)
        if n == 0 and html.count(new) >= want:
            continue  # already applied
        if n != want:
            print(f"ABORT {iid}: expected {want} occurrence(s), found {n}\n   old = {old[:120]!r}")
            bad = True
            continue
        if old in svg:
            print(f"ABORT {iid}: target lies inside the Exhibit 3 SVG")
            bad = True
            continue
        html = html.replace(old, new)
        done += 1
    if bad:
        sys.exit(1)
    return html, done


